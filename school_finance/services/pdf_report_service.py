    y = _paginate_table(c, headers, rows, y)
    y -= 4 * mm
    c.setFont("Helvetica-Bold", 9)
    c.drawString(15 * mm, y, f"Grand Total: KES {grand_total:,.2f}")
    _draw_footer(c)
    c.showPage()
    c.save()
    return file_path


